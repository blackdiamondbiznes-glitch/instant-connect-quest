export type UKey = keyof typeof UI;
export type U = (k: UKey, vars?: Record<string, string | number>) => string;

export const makeU = (lang: string): U => (k, vars) => {
  let s = tr(UI[k], lang);
  if (vars) for (const [key, v] of Object.entries(vars)) s = s.replaceAll(`{${key}}`, String(v));
  return s;
};

export const isUKey = (k: unknown): k is UKey => typeof k === "string" && k in UI;
